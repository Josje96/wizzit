// Writes the question bank + schedule to a plain-text SQL snapshot that lives in git.
// Player flags are deliberately NOT included: they stay private on the server.
//
// Output is deterministic (sorted, one row per line) so git diffs show exactly what changed.
//
// Usage: bun src/dump.ts [out=data/questions.sql]

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { openDb } from "./db.ts";

export const SNAPSHOT_PATH = join(import.meta.dir, "..", "data", "questions.sql");

/** Tables included in the snapshot, in insert order (respects foreign keys). */
export const SNAPSHOT_TABLES = [
  { name: "questions", orderBy: "id" },
  { name: "daily_sets", orderBy: "date" },
  { name: "daily_set_questions", orderBy: "date, position" },
] as const;

function sqlValue(v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number" || typeof v === "bigint") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

if (import.meta.main) {
  const out = process.argv[2] ?? SNAPSHOT_PATH;
  const db = openDb();
  const lines = [
    "-- Wizzit question bank snapshot. Generated by `bun run dump`; restore with `bun run restore`.",
    "-- Contains questions and the daily schedule. Player flags are intentionally excluded.",
    "-- Question content: CC BY-SA 4.0 (see README).",
  ];
  const counts: string[] = [];
  for (const t of SNAPSHOT_TABLES) {
    const rows = db.query<Record<string, unknown>, []>(`SELECT * FROM ${t.name} ORDER BY ${t.orderBy}`).all();
    if (!rows.length) continue;
    const cols = Object.keys(rows[0]!);
    lines.push("", `-- ${t.name}: ${rows.length} rows`);
    for (const r of rows) {
      lines.push(`INSERT INTO ${t.name} (${cols.join(", ")}) VALUES (${cols.map((c) => sqlValue(r[c])).join(", ")});`);
    }
    counts.push(`${t.name}=${rows.length}`);
  }
  writeFileSync(out, lines.join("\n") + "\n");
  db.close();
  console.log(`Wrote ${out} (${counts.join(", ")})`);
}
